CJK = re.compile(r'[\u3400-\u9fff\uf900-\ufaff]')
CLOSE = {'(' : ')', '（' : '）'}

def strip_trailing_orig(s):
    s = s.strip()
    while True:
        if not s:
            return s
        last = s[-1]
        if last not in (')', '）'):
            break
        # find matching opener
        open_ch = '(' if last == ')' else '（'
        depth = 0
        idx = -1
        for k in range(len(s) - 1, -1, -1):
            c = s[k]
            if c == last:
                depth += 1
            elif c == open_ch:
                depth -= 1
                if depth == 0:
                    idx = k
                    break
        if idx < 0:
            break
        inner = s[idx + 1:-1]
        if CJK.search(inner):
            break
        s = s[:idx].strip()
    s = re.sub(r'\s+', ' ', s).strip()
    return s

