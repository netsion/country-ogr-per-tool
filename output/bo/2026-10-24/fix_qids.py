# -*- coding: utf-8 -*-
"""P2 remediation: sync _target_orgs.json QIDs to cache ground truth,
remove bad QID bindings (EMBOL=Q12202 stroke), set OAS to correct Q123759."""
import json
import glob
import os
import sys
import io

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

D = os.path.dirname(os.path.abspath(__file__))

# 1. build cache ground truth: org_id -> cached QID
gt = {}
for f in glob.glob(os.path.join(D, '_cache', '*.json')):
    c = json.load(open(f, encoding='utf-8'))
    org = c.get('org') or {}
    oid = org.get('id')
    qid = os.path.basename(f).replace('.json', '')
    if oid:
        gt[oid] = qid

BAD_QIDS = {'Q12202', 'Q49416'}  # stroke, Anlauter river
TGT = os.path.join(D, '_target_orgs.json')
targets = json.load(open(TGT, encoding='utf-8'))

fixed, removed, oas_set = 0, 0, 0
for o in targets:
    oid = o['id']
    old = o.get('wikidata_qid')
    if oid == 'BO-INTL-002':
        o['wikidata_qid'] = 'Q123759'
        if old != 'Q123759':
            oas_set += 1
        continue
    if oid in gt:
        q = gt[oid]
        if q in BAD_QIDS:
            if old is not None:
                removed += 1
            o['wikidata_qid'] = None
        elif old != q:
            o['wikidata_qid'] = q
            fixed += 1

tmp = TGT + '.tmp'
with open(tmp, 'w', encoding='utf-8') as f:
    json.dump(targets, f, ensure_ascii=False, indent=2)
    f.flush()
    os.fsync(f.fileno())
os.replace(tmp, TGT)
json.load(open(TGT, encoding='utf-8'))  # validate
print('ground truth entries: %d | qid synced: %d | bad bindings removed: %d | OAS set: %d'
      % (len(gt), fixed, removed, oas_set))

# 2. delete garbage caches
for q in BAD_QIDS:
    p = os.path.join(D, '_cache', q + '.json')
    if os.path.exists(p):
        os.remove(p)
        print('deleted garbage cache:', q)

# 3. delete polluted profiles (regenerated by generate_profiles.py)
for oid in ('BO-CORP-002', 'BO-INTL-002'):
    p = os.path.join(D, 'orgs', oid + '.json')
    if os.path.exists(p):
        os.remove(p)
        print('deleted polluted profile:', oid)
print('OK')
